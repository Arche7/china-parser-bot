_CN_DIGITS = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}
_SIZE_RE = re.compile(r"(?<![a-z])(xxxl|xxl|xl|xxs|xs|[sml]|[2-5]xl)(?:码|号)?(?![a-z])", re.I)
_SIZE_CN_RE = re.compile(r"(?:尺码|码数|size)\s*[:：]?\s*([a-z0-9.]{1,4})", re.I)
_SHOE_RE = re.compile(r"(?<!\d)(3[5-9]|4[0-7])(?:\.5)?\s*(?:码|号)")
_EU_IT_RE = re.compile(r"(?:eu|it)\s*(3[4-9]|4[0-9]|5[0-6])", re.I)
_PCT_NEW_RE = re.compile(r"(?<!\d)(9[0-9]|8[0-9]|7[0-9])\s*新")
_CN_NEW_RE = re.compile(r"([一二三四五六七八九]|[5-9])\s*成新")


@dataclass
class Decoded:
    category: str | None = None
    weight_kg: float = 1.0
    color: str | None = None
    size: str | None = None
    condition: str | None = None
    gender: str | None = None
    notes: list[str] = field(default_factory=list)

    def summary(self) -> str:
        """'куртка · чёрный · L · как новое'"""
        parts = [p for p in (self.category, self.color, self.size and f"размер {self.size}") if p]
        return " · ".join(parts)


def _condition(text: str) -> str | None:
    if "全新" in text or "未穿" in text or "未使用" in text:
        return "новое"
    m = _PCT_NEW_RE.search(text)
    if m:
        pct = int(m.group(1))
        if pct >= 99:
            return "как новое"
        if pct >= 95:
            return f"отличное ({pct}%)"
        if pct >= 90:
            return f"хорошее ({pct}%)"
        return f"с износом ({pct}%)"
    m = _CN_NEW_RE.search(text)
    if m:
        value = m.group(1)
        tens = _CN_DIGITS.get(value) or int(value)
        if tens >= 9:
            return "хорошее (90%)"
        if tens >= 8:
            return "с износом (80%)"
        return f"с заметным износом ({tens * 10}%)"
    if "二手" in text:
        return "б/у"
    return None


def _size(text: str, category: str | None) -> str | None:
    m = _SIZE_CN_RE.search(text)
    if m:
        return m.group(1).upper()
    if category in {"кроссовки", "кеды", "ботинки", "обувь", "туфли", "лоферы", "шлёпанцы", "сандалии"}:
        m = _SHOE_RE.search(text) or _EU_IT_RE.search(text)
        if m:
            return m.group(0).replace("码", "").replace("号", "").upper().strip()
    m = _EU_IT_RE.search(text)
    if m:
        return m.group(0).upper().replace(" ", "")
    # Буквенные размеры ищем только рядом с 码/号 или как отдельное слово
    for m in _SIZE_RE.finditer(text):
        token = m.group(1).upper()
        # «S» и «M» слишком часто встречаются внутри брендов/моделей — берём
        # их, только если сразу после стоит 码 или 号
        if token in {"S", "M"} and not re.match(r"(码|号)", text[m.end(1):m.end(1) + 1]):
            continue
        return token
    return None


def decode(title: str) -> Decoded:
    text = title.lower()
    result = Decoded()
    for cn, ru, weight in CATEGORIES:
        if cn in text:
            result.category, result.weight_kg = ru, weight
            break
    for cn, ru in COLORS:
        if f"{cn}色" in text:
            result.color = ru
            break
    result.size = _size(text, result.category)
    result.condition = _condition(text)
    if "男" in text and "女" not in text:
        result.gender = "мужское"
    elif "女" in text and "男" not in text:
        result.gender = "женское"
    seen = set()
    for cn, ru in NOTES:
        if cn in text and ru not in seen:
            # «новое с бирками» уже включает «есть бирки»
            if ru == "есть бирки" and "новое с бирками" in seen:
                continue
            seen.add(ru)
            result.notes.append(ru)
    return result


def city_ru(city: str | None) -> str | None:
    """'上海' -> 'Шанхай', '浙江杭州' -> 'Ханчжоу'. Незнакомое — как есть."""
    if not city:
        return None
    city = str(city).strip()
    # В словаре сначала идут города, потом провинции — берём первое совпадение
    for cn, ru in CITIES.items():
        if cn in city:
            return ru
    return city


def strip_noise(title: str) -> str:
    """
    Убирает из заголовка эмодзи, хэштеги и повторы — для варианта
    «показать оригинал».
    """
    title = re.sub(r"#\S+", " ", title)
    title = re.sub(r"[\U0001F300-\U0001FAFF☀-➿]", " ", title)
    title = re.sub(r"[【】\[\]「」『』|｜]+", " ", title)
    title = re.sub(r"\s+", " ", title)
    return title.strip()


def has_chinese(text: str) -> bool:
    return bool(re.search(r"[一-鿿]", text))
